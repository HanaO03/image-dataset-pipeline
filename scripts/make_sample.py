"""
Build a small, committable sample of the exported dataset.

The full export copies every image into data/output/images/, which is ~94 MB —
too heavy to put in a repository, and regenerable in one command anyway. This
writes a handful of real images per class and split into
data/output/sample_images/ so a reviewer can look at actual photographs without
cloning a large repo.

    python scripts/make_sample.py            # 4 images per class per split
    python scripts/make_sample.py --per 8
"""

from __future__ import annotations

import argparse
import json
import shutil
from collections import defaultdict
from pathlib import Path

OUTPUT = Path("data/output")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--per", type=int, default=4,
                        help="images per (class, split) pair")
    args = parser.parse_args()

    manifest = json.loads((OUTPUT / "manifest.json").read_text(encoding="utf-8"))
    sample_dir = OUTPUT / "sample_images"
    if sample_dir.exists():
        shutil.rmtree(sample_dir)

    # Sorted, then take the first N — deterministic, so regenerating the sample
    # produces the same files rather than an arbitrary new set each time.
    buckets: dict[tuple[str, str], list[dict]] = defaultdict(list)
    for entry in sorted(manifest["images"], key=lambda e: e["checksum"]["value"]):
        buckets[(entry["label"], entry["split"])].append(entry)

    picked: list[dict] = []
    for key in sorted(buckets):
        picked.extend(buckets[key][: args.per])

    total_bytes = 0
    for entry in picked:
        source = OUTPUT / entry["path"]
        if not source.is_file():
            print(f"  missing, skipped: {entry['path']}")
            continue
        destination = sample_dir / entry["split"] / entry["label"] / source.name
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(source, destination)
        total_bytes += destination.stat().st_size

    (sample_dir / "README.txt").write_text(
        "Sample of the exported dataset — a few real images per class and split.\n"
        "The complete image set is regenerated by `docker compose up`; only this\n"
        "sample is committed, to keep the repository small.\n"
        "Authoritative records for every image are in ../manifest.json,\n"
        "../dataset.parquet and ../dataset.csv.\n"
        f"\nSampled {len(picked)} of {manifest['n_images']} images.\n",
        encoding="utf-8",
    )

    print(f"wrote {len(picked)} images ({total_bytes / 1e6:.1f} MB) to {sample_dir}")


if __name__ == "__main__":
    main()
